package com.ivy.legacy.planned

import com.ivy.data.model.IntervalType
import com.ivy.legacy.domain.deprecated.logic.PlannedOccurrences
import com.ivy.legacy.domain.deprecated.logic.PlannedOccurrences.Schedule
import io.kotest.matchers.collections.shouldBeEmpty
import io.kotest.matchers.collections.shouldHaveSize
import io.kotest.matchers.shouldBe
import org.junit.Test
import java.time.Instant

/** Automatic top-ups ([PlannedOccurrences.extend]), which run on every app start. */
class PlannedOccurrencesExtendTest {
    private val monthlySince2023 = Schedule(day("2023-01-05"), IntervalType.MONTH, 1)
    private val firstUpcomingOfMonthlySince2023 = day("2026-11-05")

    private fun extend(rule: Schedule, upcoming: List<Instant>, paidCount: Int = 0) =
        PlannedOccurrences.extend(rule, upcomingDueDates = upcoming, paidCount = paidCount, now = NOW)

    @Test
    fun `extend continues after the last upcoming instance up to the window`() {
        val rule = Schedule(day("2020-03-15"), IntervalType.MONTH, 1)

        val added = extend(rule, listOf(day("2026-11-15"), day("2026-12-15")))

        added.first() shouldBe day("2027-01-15")
        added.last() shouldBe day("2029-10-15")
    }

    @Test
    fun `extend adds nothing when the window is full`() {
        val rule = Schedule(day("2026-11-05"), IntervalType.MONTH, 1)
        val upcoming = PlannedOccurrences.regenerate(rule, paidCount = 0, now = NOW)

        extend(rule, upcoming).shouldBeEmpty()
    }

    @Test
    fun `extend respects the upcoming limit`() {
        val start = day("2026-10-01")
        val rule = Schedule(start, IntervalType.DAY, 1)
        val upcoming = (0L until 70L).map { start.plusSeconds(it * 86_400) }

        extend(rule, upcoming) shouldHaveSize 2
    }

    @Test
    fun `extend never adds a second payment in a month of a drifted older instance`() {
        // Instances generated by the old code drifted from the 31st to the 28th.
        val rule = Schedule(day("2027-01-31"), IntervalType.MONTH, 1)
        val oldUpcoming = listOf(rule.start, day("2027-02-28"), day("2027-03-28"))

        extend(rule, oldUpcoming).first() shouldBe day("2027-04-30")
    }

    @Test
    fun `occurrences skipped by the user are not recreated when everything else was paid`() {
        // 20 paid; the other past months were skipped, which deletes their instances.
        val added = extend(monthlySince2023, upcoming = emptyList(), paidCount = 20)

        added.first() shouldBe firstUpcomingOfMonthlySince2023
    }

    @Test
    fun `an old overdue instance doesn't make the top-up back-fill past months`() {
        val added = extend(monthlySince2023, upcoming = listOf(day("2024-03-05")))

        added.first() shouldBe firstUpcomingOfMonthlySince2023
    }

    @Test
    fun `payments made ahead of time are still respected`() {
        // Paid 12 instances from January 2026: the next one is January 2027, not November 2026.
        val rule = Schedule(day("2026-01-01"), IntervalType.MONTH, 1)

        extend(rule, upcoming = emptyList(), paidCount = 12).first() shouldBe day("2027-01-01")
    }
}
